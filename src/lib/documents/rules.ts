const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isUuid(value: unknown): value is string {
  return typeof value === "string" && UUID_RE.test(value);
}

/** Returns a YYYY-MM-DD string for a real calendar date, otherwise null. */
export function cleanDate(value: unknown): string | null {
  if (typeof value !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return null;
  const d = new Date(`${value}T00:00:00Z`);
  return Number.isNaN(d.getTime()) || d.toISOString().slice(0, 10) !== value ? null : value;
}

/**
 * The storage path a caller may upload to is always
 * `<their user id>/<their passport id>/<random uuid>.<ext>` — generated by
 * the server, and re-checked against this pattern before it is accepted.
 */
export function isOwnStoragePath(path: unknown, userId: string, passportId: string): path is string {
  if (typeof path !== "string") return false;
  const match = /^([^/]+)\/([^/]+)\/([0-9a-f-]{36})\.(pdf|jpg|png)$/i.exec(path);
  return !!match && match[1] === userId && match[2] === passportId && isUuid(match[3]);
}

// The stored content type comes from the BYTES, never from what the
// browser declared — an HTML/JS payload labelled application/pdf must not
// be stored and later rendered from a signed URL.
export function sniffContentType(bytes: Uint8Array): string | null {
  if (bytes.length >= 5 && bytes[0] === 0x25 && bytes[1] === 0x50 && bytes[2] === 0x44 && bytes[3] === 0x46 && bytes[4] === 0x2d) {
    return "application/pdf"; // "%PDF-"
  }
  if (bytes.length >= 8 && bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4e && bytes[3] === 0x47
    && bytes[4] === 0x0d && bytes[5] === 0x0a && bytes[6] === 0x1a && bytes[7] === 0x0a) {
    return "image/png";
  }
  if (bytes.length >= 3 && bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) {
    return "image/jpeg";
  }
  return null;
}
